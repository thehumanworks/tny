#!/bin/sh
# Embed the tny Python package (python/tny/*.py) into a C header for the tool
# host (src/core/tool_host.c, ADR 0218). POSIX sh + od, so building tny needs
# no Python. Usage: embed_python.sh OUT.h python/tny/__init__.py ...
set -eu
out=$1
shift
if [ $# -eq 0 ]; then
    echo 'embed_python.sh: no python/tny/*.py sources (is python/ in the tree?)' >&2
    exit 1
fi
tmp=$out.tmp
{
    echo '/* Generated by scripts/embed_python.sh from python/tny; do not edit. */'
    echo '#include <stddef.h>'
    i=0
    for f in "$@"; do
        printf 'static const unsigned char tny_py_src_%d[] = {\n' "$i"
        # awk splits on any whitespace: BSD od pads lines differently from GNU.
        od -An -v -tu1 "$f" | awk 'NF { for (i = 1; i <= NF; i++) printf "%s,", $i; print "" }'
        printf '0};\n'
        i=$((i + 1))
    done
    echo 'static const struct {'
    echo '    const char *name;'
    echo '    int is_package;'
    echo '    const unsigned char *source;'
    echo '} tny_python_package[] = {'
    i=0
    for f in "$@"; do
        base=$(basename "$f" .py)
        if [ "$base" = "__init__" ]; then
            printf '    {"tny", 1, tny_py_src_%d},\n' "$i"
        else
            printf '    {"tny.%s", 0, tny_py_src_%d},\n' "$base" "$i"
        fi
        i=$((i + 1))
    done
    echo '};'
} > "$tmp"
mv "$tmp" "$out"
